# ---- FORM の 'row' を解釈するヘルパー（xlsx・md 生成で共有） ----

def clean_label(text):
    """接続語付きの静的文字を選択肢ラベルに正規化（「その他（」→「その他」、「）　具体」→「具体」など）。"""
    return text.strip(" 　（）()「」：:／/→ ").strip()


def is_closer(text):
    """純粋な閉じ括弧など（読み飛ばしてよい接続語）か。"""
    return clean_label(text) == ""


def split_check_row(segments):
    """チェック肢を含む 'row' を (prompt, options) に分解。

    options は (kind, label) のリスト。kind は 'check'（未/済の選択肢）か
    'write'（その他・自由記述・氏名など、選択＋自由記述で受ける項目）。
    """
    idx = 0
    prompt_parts, prompt_has_field = [], False
    while idx < len(segments) and segments[idx][0] != "c":
        seg = segments[idx]
        if seg[0] == "t":
            prompt_parts.append(seg[1])
        elif seg[0] == "f":
            prompt_has_field = True
        idx += 1
    prompt = "".join(prompt_parts).strip().replace("（）", "（　）")

    options = []
    if prompt_has_field:  # 「その他（____）：紙/Excel/…」→ 内容の記入欄を先頭に
        options.append(("write", "内容を記入"))

    rest = segments[idx:]
    j = 0
    while j < len(rest):
        kind = rest[j][0]
        if kind == "c":
            options.append(("check", rest[j][1]))
            j += 1
        elif kind == "t":
            if j + 1 < len(rest) and rest[j + 1][0] == "f":
                label = clean_label(rest[j][1]) or "自由記述"
                options.append(("write", label))
                j += 2
                if j < len(rest) and rest[j][0] == "t" and is_closer(rest[j][1]):
                    j += 1  # 閉じ括弧などを読み飛ばす
            else:
                j += 1  # 単独の接続語（「）」「／」等）は読み飛ばす
        else:  # 先頭以外に出てくる単独の f
            options.append(("write", "自由記述"))
            j += 1
    return prompt, options


def freetext_items(segments):
    """記入欄のみの 'row' を (label, has_input) の並びに分解。

    記入欄の直前までの静的文字をラベルにする。末尾に残った静的文字（※注記など）は
    has_input=False のラベル行として返す。
    """
    items, pending = [], ""
    for seg in segments:
        if seg[0] == "t":
            pending = (pending + seg[1]).strip()
        elif seg[0] == "f":
            items.append((pending, True))
            pending = ""
    if pending:
        items.append((pending, False))
    return items

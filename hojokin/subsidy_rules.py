@dataclass(frozen=True)
class SubsidyRules:
    rule_id: str
    bonus1_window: tuple[tuple[int, int], ...]
    bonus2_base_ym: tuple[int, int]
    bonus2_threshold_yen: int
    min_wage_before: Mapping[str, int]
    min_wage_after: Mapping[str, int]
    forms_dir: str
    ledger_template_path: str


def rules_for_round(call_round: int = 6) -> SubsidyRules:
    if isinstance(call_round, bool) or not isinstance(call_round, int) or call_round < 1:
        raise ValueError('公募回は1以上の整数で指定してください。')
    new = call_round >= 7
    start = 2025 if new else 2024
    window = tuple([(start, m) for m in (10, 11, 12)] + [(start + 1, m) for m in range(1, 10)])
    return SubsidyRules(
        rule_id='2026_rounds_7_plus' if new else '2026_rounds_1_6',
        bonus1_window=window,
        bonus2_base_ym=(2026, 6) if new else (2025, 7),
        bonus2_threshold_yen=55 if new else 63,
        min_wage_before=MappingProxyType(MIN_WAGE_R7 if new else MIN_WAGE_R6),
        min_wage_after=MappingProxyType(MIN_WAGE_R8 if new else MIN_WAGE_R7),
        forms_dir='補助金加点/第7次以降' if new else '補助金加点',
        ledger_template_path=('ツール/第7次以降/加点判定用賃金台帳テンプレート.xlsx' if new
                              else 'ツール/加点判定用賃金台帳テンプレート.xlsx'),
    )


def legal_minimum_bounds(prefecture: str, ym: tuple[int, int]) -> tuple[int, int, bool]:
    """月全体に適用し得る法定額の下限/上限と、期間別確認の必要有無。

    月途中発効又は発効日未確認では単一額へ丸めない。上限以上の入力なら時点差による
    最賃割れの疑義はなく、上下限の間は個別確認が必要（通常手当の定義確認は別途）。
    """
    if prefecture not in MIN_WAGE_R6:
        return 0, 0, True
    first = date(ym[0], ym[1], 1)
    last = date(ym[0], ym[1], monthrange(*ym)[1])
    if first >= date(2027, 10, 1):
        return 0, 0, True  # R9以降へR8額を黙って延長しない。
    previous = 0
    for amounts, effective in ((MIN_WAGE_R6, EFFECTIVE_R6),
                               (MIN_WAGE_R7, EFFECTIVE_R7),
                               (MIN_WAGE_R8, EFFECTIVE_R8)):
        amount = amounts[prefecture]
        stamp = effective.get(prefecture)
        year = 2024 if amounts is MIN_WAGE_R6 else 2025 if amounts is MIN_WAGE_R7 else 2026
        if last < date(year, 10, 1):
            break
        if stamp is None:
            return previous, amount, True
        when = date.fromisoformat(stamp)
        if when <= first:
            previous = amount
        elif when <= last:
            return previous, amount, True
        else:
            break
    return previous, previous, previous == 0
